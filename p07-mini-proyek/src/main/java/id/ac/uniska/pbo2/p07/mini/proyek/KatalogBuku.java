    private void saring() {
        String kata = cariField.getText().trim();
        if (kata.isEmpty()) {
            sorter.setRowFilter(null);
        } else {
            // (?i): huruf besar dan kecil dianggap sama; 0, 1, 2: kolom yang dicari
            sorter.setRowFilter(RowFilter.regexFilter("(?i)" + Pattern.quote(kata), 0, 1, 2));
        }
        perbaruiStatus();
    }

    /**
     * Mengubah nomor baris tampilan menjadi nomor baris model, karena tabel
     * dapat diurutkan dan disaring.
     */
    private int barisTerpilih() {
        int barisTampilan = daftarTable.getSelectedRow();
        if (barisTampilan < 0) {
            return -1;
        }
        return daftarTable.convertRowIndexToModel(barisTampilan);
    }

    private void tambah() {
        Buku baru = new DialogBuku(this, "Tambah Buku", null).tampilkan();
        if (baru != null) {
            model.tambah(baru);
            perbaruiStatus();
        }
    }

    private void ubah() {
        int baris = barisTerpilih();
        if (baris < 0) {
            return;
        }
        Buku hasil = new DialogBuku(this, "Ubah Katalog Buku", model.get(baris)).tampilkan();
        if (hasil != null) {
            model.ubah(baris, hasil);
            if (hasil != null) {
                model.ubah(baris, hasil);
                perbaruiStatus();
}
        }
    }

    private void hapus() {
        int baris = barisTerpilih();
        if (baris < 0) {
            return;
        }
        String judul = model.get(baris).judul();
        int jawab = JOptionPane.showConfirmDialog(this, "Hapus Buku " + judul + "?",
                "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (jawab == JOptionPane.YES_OPTION) {
            model.hapus(baris);
            perbaruiStatus();
        }
    }

    private void perbaruiTombol() {
        boolean adaPilihan = daftarTable.getSelectedRow() >= 0;
        ubahButton.setEnabled(adaPilihan);
        hapusButton.setEnabled(adaPilihan);
        ubahItem.setEnabled(adaPilihan);
        hapusItem.setEnabled(adaPilihan);
    }

    private void perbaruiStatus() {
        int jumlahTersedia = 0;

    for (int i = 0; i < model.getRowCount(); i++) {
        if (model.get(i).kategori() == Kategori.TERSEDIA) {
            jumlahTersedia++;
        }
    }
        statusLabel.setText("Menampilkan " + daftarTable.getRowCount()
                + " dari " + model.getRowCount() + " buku");
        digitLabel.setText(jumlahTersedia + " buku tersedia");
    }
    

